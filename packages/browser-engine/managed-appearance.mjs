import fs from 'node:fs';
import path from 'node:path';

// Only called for this manager's closed, owned Chrome profile before launch.
export function configureManagedChrome(session) {
  if(session.mode!=='managed'||session.browser!=='chrome')return [];
  const folder=path.join(session.profile,'Default');
  fs.mkdirSync(folder,{recursive:true});
  const file=path.join(folder,'Preferences');
  const prefs=fs.existsSync(file)?JSON.parse(fs.readFileSync(file,'utf8')):{};
  prefs.profile={...prefs.profile,name:'工作台 · '+session.label};
  prefs.signin={...prefs.signin,allowed:false,allowed_on_next_startup:false};
  fs.writeFileSync(file,JSON.stringify(prefs));
  return ['--disable-sync','--install-autogenerated-theme=35,79,72'];
}
