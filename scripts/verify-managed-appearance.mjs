import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {SessionManager,projectRoot} from '../packages/browser-engine/sessions.mjs';

const root=path.join(projectRoot,'work/appearance-acceptance');
const manager=new SessionManager({root});
const id='appearance-fixture';
if(!manager.list().some(s=>s.id===id))manager.create({id,label:'界面验收'});
try{
  const c=await manager.start(id);
  const page=await c.tabs.openExact('chrome://settings/syncSetup');
  const expression=`new Promise(resolve=>chrome.settingsPrivate.getPref('signin.allowed_on_next_startup',p=>resolve({value:p?.value,error:chrome.runtime.lastError?.message})))`;
  const pref=await c.cdp.sendToTarget(page.targetId,'Runtime.evaluate',{expression,awaitPromise:true,returnByValue:true});
  assert.equal(pref.result.result.value?.value,false,JSON.stringify(pref.result));
  const version=await c.cdp.send('Browser.getVersion');
  await manager.close(id);
  const prefs=JSON.parse(await fs.readFile(path.join(manager.get(id).profile,'Default/Preferences'),'utf8'));
  assert.equal(prefs.profile.name,'工作台 · 界面验收');
  assert.equal(prefs.autogenerated.theme.color>>>0,0xff234f48);
  const result={passed:true,browser:version.result.product,
    chrome_signin_allowed:pref.result.result.value.value,profile_name:prefs.profile.name,
    installed_theme_rgb:[35,79,72],tested_in_background:true};
  await fs.mkdir(path.join(projectRoot,'outputs/appearance-acceptance'),{recursive:true});
  await fs.writeFile(path.join(projectRoot,'outputs/appearance-acceptance/result.json'),JSON.stringify(result,null,2));
  console.log(JSON.stringify(result,null,2));
}finally{
  if(manager.contexts.get(id)?.cdp.connected)await manager.close(id);
}
